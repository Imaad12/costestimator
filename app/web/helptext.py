from __future__ import annotations

import re


def norm(text: str) -> str:
    """Must stay identical to `norm` in static/help.js."""
    t = text.lower()
    t = re.sub(r"\([^)]*\)", " ", t)
    t = re.sub(r"[*:·]", " ", t)
    t = re.sub(r"\d[\d,.]*", " ", t)
    t = re.sub(r"[^a-z0-9%&/+ -]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


